//! Bounded browser-login subprocesses. No authorization output reaches logs.
use std::{
    io::Read,
    process::{Command, Stdio},
    sync::{
        atomic::{AtomicBool, Ordering},
        mpsc, Arc,
    },
    time::{Duration, Instant},
};

const OUTPUT_LIMIT: usize = 16 * 1024;

/// The watchdog is in the login process group, so a Desktop crash still ends
/// login and its descendants. Arguments are positional, never shell source.
#[cfg(unix)]
const SUPERVISOR: &str = r#"
parent="$1"; seconds="$2"; shift 2
group="$$"
(
  elapsed=0
  while kill -0 "$parent" 2>/dev/null && [ "$elapsed" -lt "$seconds" ]; do
    sleep 1
    elapsed=$((elapsed + 1))
  done
  /bin/kill -KILL -- "-$group" 2>/dev/null
) </dev/null >/dev/null 2>&1 &
"$@" 2>&1
exit $?
"#;

pub(super) fn command(executable: &std::path::Path, args: &[&str], timeout: Duration) -> Command {
    #[cfg(unix)]
    {
        use std::os::unix::process::CommandExt;
        let mut command = Command::new("/bin/sh");
        command
            .arg("-c")
            .arg(SUPERVISOR)
            .arg("subscription-login")
            .arg(std::process::id().to_string())
            .arg(timeout.as_secs().max(1).to_string())
            .arg(executable)
            .args(args)
            .process_group(0);
        command
    }
    #[cfg(not(unix))]
    {
        let _ = timeout;
        let mut command = Command::new(executable);
        command.args(args);
        command
    }
}

pub(super) fn kill_group(id: u32) -> Result<(), String> {
    #[cfg(unix)]
    {
        // Command is absolute and the group id is generated by the OS.
        let status = Command::new("/bin/kill")
            .args(["-KILL", "--", &format!("-{id}")])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .map_err(|_| "Could not stop account login process")?;
        if !status.success() {
            // ESRCH is expected when the watchdog already killed the group.
            let alive = Command::new("/bin/kill")
                .args(["-0", "--", &format!("-{id}")])
                .stdout(Stdio::null())
                .stderr(Stdio::null())
                .status()
                .map_err(|_| "Could not inspect account login process")?;
            if alive.success() {
                return Err("Could not stop account login process group".into());
            }
        }
        Ok(())
    }
    #[cfg(not(unix))]
    {
        let _ = id;
        Err("Account login process containment unavailable".into())
    }
}

pub(super) fn run(
    mut command: Command,
    timeout: Duration,
    cancelled: &Arc<AtomicBool>,
    capture: bool,
) -> Result<Vec<u8>, String> {
    if !cfg!(unix) {
        return Err("Account login process containment unavailable".into());
    }
    command.stdin(Stdio::null()).stderr(Stdio::null());
    command.stdout(if capture {
        Stdio::piped()
    } else {
        Stdio::null()
    });
    let mut child = command
        .spawn()
        .map_err(|_| "Could not start provider login command")?;
    let pid = child.id();
    let output = if let Some(stdout) = child.stdout.take() {
        let (sender, receiver) = mpsc::channel();
        std::thread::spawn(move || {
            let mut bytes = Vec::new();
            let result = stdout
                .take((OUTPUT_LIMIT + 1) as u64)
                .read_to_end(&mut bytes)
                .map(|_| bytes)
                .map_err(|_| "Could not read provider status".to_string());
            let _ = sender.send(result);
        });
        Some(receiver)
    } else {
        None
    };
    let started = Instant::now();
    let result = loop {
        if cancelled.load(Ordering::SeqCst) {
            break Err("Login cancelled".to_string());
        }
        if started.elapsed() >= timeout {
            break Err("Provider login timed out; reconnect to retry".to_string());
        }
        match child.try_wait() {
            Ok(Some(status)) => {
                break if status.success() {
                    Ok(())
                } else {
                    Err("Provider command failed; check login or connection and reconnect".into())
                }
            }
            Err(_) => break Err("Could not inspect provider login process".into()),
            Ok(None) => std::thread::sleep(Duration::from_millis(25)),
        }
    };
    let cleanup = kill_group(pid);
    if cleanup.is_err() {
        // Preserve the containment error, but do not wait on an un-killed
        // leader if the group signal itself failed.
        let _ = child.kill();
    }
    let reap = child
        .wait()
        .map_err(|_| "Could not reap provider login process".to_string());
    cleanup?;
    reap?;
    result?;
    match output {
        Some(receiver) => {
            let bytes = receiver
                .recv_timeout(Duration::from_secs(1))
                .map_err(|_| "Provider status output did not close".to_string())??;
            if bytes.len() > OUTPUT_LIMIT {
                return Err("Provider status output exceeded limit".into());
            }
            Ok(bytes)
        }
        None => Ok(Vec::new()),
    }
}
