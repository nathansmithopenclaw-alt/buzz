#!/usr/bin/env bash
# Install the vendored, pinned Track-A ACP adapter (L4.1).
# - verifies the committed tarball against PROVENANCE.json BEFORE installing
# - installs via npm from the file: pin (never hand-edited node_modules)
# - writes a shim at ~/.buzz/agents/bin/claude-agent-acp (override dir with
#   BUZZ_AGENT_BIN_DIR). Put that dir ahead of any global npm bin on PATH.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
V="$REPO_ROOT/vendor/acp-adapter"
PROV="$V/PROVENANCE.json"
TARBALL="$(python3 -c "import json;print(json.load(open('$PROV'))['tarball'])")"
EXPECT_SHA="$(python3 -c "import json;print(json.load(open('$PROV'))['tarball_sha256'])")"
EXPECT_VER="$(python3 -c "import json;print(json.load(open('$PROV'))['version'])")"

ACTUAL_SHA="$(shasum -a 256 "$V/$TARBALL" | awk '{print $1}')"
if [[ "$ACTUAL_SHA" != "$EXPECT_SHA" ]]; then
    echo "FAIL: vendored tarball hash mismatch" >&2
    echo "  expected $EXPECT_SHA" >&2
    echo "  actual   $ACTUAL_SHA" >&2
    echo "Refusing to install unverified bytes. Rebuild per PROVENANCE.json." >&2
    exit 1
fi
echo "tarball hash OK: $ACTUAL_SHA"

( cd "$V" && npm install --no-audit --no-fund --omit=dev )

PKG="$V/node_modules/@agentclientprotocol/claude-agent-acp"
ACTUAL_VER="$(node -p "require('$PKG/package.json').version")"
if [[ "$ACTUAL_VER" != "$EXPECT_VER" ]]; then
    echo "FAIL: installed version $ACTUAL_VER != pinned $EXPECT_VER" >&2
    exit 1
fi
echo "installed version OK: $ACTUAL_VER"

BIN_DIR="${BUZZ_AGENT_BIN_DIR:-$HOME/.buzz/agents/bin}"
mkdir -p "$BIN_DIR"
SHIM="$BIN_DIR/claude-agent-acp"
cat > "$SHIM" <<EOF
#!/bin/bash
# Vendored Track-A adapter shim (generated by scripts/install-vendored-acp-adapter.sh)
exec node "$PKG/dist/index.js" "\$@"
EOF
chmod 755 "$SHIM"

echo "shim written: $SHIM"
echo "NOTE: ensure $BIN_DIR precedes the global npm bin on PATH for the harness;"
echo "      running sessions keep their existing adapter until respawn."
